"""Typed scientific contracts shared across the benchmark."""

from __future__ import annotations

from enum import StrEnum


class EvidenceClass(StrEnum):
    MEASURED = "MEASURED"
    DERIVED = "DERIVED"
    SIMULATED = "SIMULATED"
    EXTERNAL = "EXTERNAL"
    PROJECTED = "PROJECTED"
    PENDING = "PENDING"


class FailureCategory(StrEnum):
    ENGINEERING_FAILURE = "ENGINEERING_FAILURE"
    PACKAGE_INCOMPATIBILITY = "PACKAGE_INCOMPATIBILITY"
    NUMERICAL_FAILURE = "NUMERICAL_FAILURE"
    STATISTICAL_FAILURE = "STATISTICAL_FAILURE"
    SCIENTIFIC_GATE_FAILURE = "SCIENTIFIC_GATE_FAILURE"
    EXTERNAL_BLOCKER = "EXTERNAL_BLOCKER"
    PROTOCOL_INVALIDATION = "PROTOCOL_INVALIDATION"


class PhaseStatus(StrEnum):
    COMPLETE = "COMPLETE"
    GATED = "GATED"
    INVALID = "INVALID"
    FAILED = "FAILED"


class ProjectDecision(StrEnum):
    PROMOTE_AWARE = "PROMOTE_AWARE"
    RETAIN_FIXED_BASELINE = "RETAIN_FIXED_BASELINE"
    INCONCLUSIVE = "INCONCLUSIVE"
    INVALID_PROTOCOL = "INVALID_PROTOCOL"
